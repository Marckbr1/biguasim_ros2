#!/usr/bin/env python3
"""Writes a copy of a simulator config whose spawn (location/rotation of the
main agent) is the FIRST waypoint of a route, so the ROV starts on the route
instead of having to transit to it (and, with yaw = the waypoint's yaw_deg,
already facing the first leg).

Used automatically by start_collection.sh / test_route.sh. Prints the path
of the generated config on stdout.

Usage:
  python3 tools/spawn_at_first_waypoint.py waypoints/mi_ruta.yaml \
      --base config/simulator_rov.yaml --out config/generated/simulator_mi_ruta.yaml
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from biguasim_dataset_standalone.trajectories import load_waypoints_csv  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("trajectory_yaml")
    ap.add_argument("--base", default="config/simulator_rov.yaml")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    traj_path = Path(args.trajectory_yaml)
    traj = yaml.safe_load(traj_path.read_text())
    csv_path = (traj_path.resolve().parent / traj["waypoints_csv_path"]).resolve()
    first = load_waypoints_csv(str(csv_path))[0]

    text = Path(args.base).read_text()
    # Agent-level keys are indented 4 spaces (sensor 'location:' keys are 8).
    new_loc = f"    location: [{first.x}, {first.y}, {first.z}]   # spawn = waypoint 1 of {csv_path.name}"
    new_rot = f"    rotation: [0.0, 0.0, {first.yaw_deg}]   # yaw = yaw_deg of waypoint 1"
    text, n_loc = re.subn(r"(?m)^    location:.*$", new_loc, text)
    text, n_rot = re.subn(r"(?m)^    rotation:.*$", new_rot, text)
    if n_loc != 1 or n_rot != 1:
        sys.exit(f"ERROR: expected exactly one agent-level 'location:'/'rotation:' in {args.base} "
                 f"(found {n_loc}/{n_rot}).")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"# GENERATED by tools/spawn_at_first_waypoint.py from {args.base} -- do not edit.\n" + text)
    print(out)


if __name__ == "__main__":
    main()
